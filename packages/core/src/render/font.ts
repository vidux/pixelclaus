function glyphFor(font: BitmapFont, ch: string): readonly string[] {
  const g = font.glyphs[ch] ?? (font.caseFold ? font.glyphs[ch.toUpperCase()] : undefined);
  return g ?? font.glyphs['?'] ?? font.glyphs[' ']!;
}

export interface TextLayout {
  width: number;
  height: number;
}

/** Size of a (possibly multi-line) string in font pixels. */
export function measureText(font: BitmapFont, text: string, spacing = 1, lineSpacing = 1): TextLayout {
  const lines = text.split('\n');
  const maxLen = Math.max(...lines.map((l) => l.length));
  return {
    width: maxLen === 0 ? 0 : maxLen * font.width + (maxLen - 1) * spacing,
    height: lines.length * font.height + (lines.length - 1) * lineSpacing,
  };
}

/** Invoke `plot` for every ink pixel of `text` laid out at (x, y). */
export function forEachTextPixel(
  font: BitmapFont,
  text: string,
  x: number,
  y: number,
  plot: (px: number, py: number) => void,
  spacing = 1,
  lineSpacing = 1,
): void {
  const lines = text.split('\n');
  lines.forEach((line, li) => {
    const oy = y + li * (font.height + lineSpacing);
    for (let i = 0; i < line.length; i++) {
      const g = glyphFor(font, line[i]!);
      const ox = x + i * (font.width + spacing);
      for (let gy = 0; gy < g.length; gy++) {
        const row = g[gy]!;
        for (let gx = 0; gx < row.length; gx++) if (row[gx] === '#') plot(ox + gx, oy + gy);
      }
    }
  });
}
